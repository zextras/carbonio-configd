# Shared helpers of run-legacy.sh / run-configd.sh (sourced, not executed).

PARITY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARITY_IMAGE="${PARITY_IMAGE:-localhost/carbonio-parity:noble}"
PARITY_FQDN="${PARITY_FQDN:-mail.parity.test}"
PARITY_CONFIG="${PARITY_CONFIG:-${PARITY_DIR}/config/single-node.config}"
BOOT_TIMEOUT="${BOOT_TIMEOUT:-120}"

log() { printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }

# start_container NAME: systemd as PID 1, FQDN hostname, hosts file written below.
start_container() {
  local name="$1"
  podman rm -f "${name}" >/dev/null 2>&1 || true
  # --no-hosts: /etc/hosts is generated by prepare_container (FQDN first).
  # --tmpfs /tmp: mailbox/zmsetup scratch space, like a real host.
  podman run -d --name "${name}" --systemd=always --no-hosts \
    --hostname "${PARITY_FQDN}" \
    --tmpfs /tmp:rw,exec,mode=1777 \
    "${PARITY_IMAGE}" >/dev/null || die "podman run failed (image built? ./build.sh)"
  local i
  for ((i = 0; i < BOOT_TIMEOUT; i++)); do
    # "degraded" is fine: some units are masked/unsupported in containers.
    case "$(podman exec "${name}" systemctl is-system-running 2>/dev/null || true)" in
      running | degraded) return 0 ;;
    esac
    sleep 1
  done
  die "systemd did not reach running/degraded in ${BOOT_TIMEOUT}s"
}

# prepare_container NAME: everything the distro/hypervisor would normally
# provide and that both bootstrap paths need identically.
prepare_container() {
  local name="$1" ip
  ip="$(podman exec "${name}" hostname -I | awk '{print $1}')"
  [[ -n "${ip}" ]] || ip=127.0.1.1
  # FQDN + short name resolvable (CE docs "Setting Hostname"); /etc/hosts is a
  # bind mount only when podman manages it; with --no-hosts it is a plain file.
  podman exec "${name}" bash -c \
    "printf '127.0.0.1 localhost\n${ip} ${PARITY_FQDN} ${PARITY_FQDN%%.*}\n' > /etc/hosts"
  podman exec "${name}" hostnamectl set-hostname "${PARITY_FQDN}" 2>/dev/null || true
  # Container workaround of the CE image pipeline (infra-carbonio-ce-images):
  # the default 80 GiB mdb map does not fit the container.
  podman exec "${name}" runuser -u zextras -- /opt/zextras/bin/zmlocalconfig \
    -e ldap_db_maxsize=99345920 -e ldap_accesslog_maxsize=99345920 >/dev/null
  podman exec "${name}" sed -i 's/olcDbMaxsize: 85899345920/olcDbMaxsize: 85899345/' \
    "/opt/zextras/common/etc/openldap/zimbra/config/cn=config/olcDatabase={2}mdb.ldif"
  # Same input file for both runs; 0600 because it holds passwords.
  podman cp "${PARITY_CONFIG}" "${name}:/opt/product.config"
  podman exec "${name}" chown root:root /opt/product.config
  podman exec "${name}" chmod 0600 /opt/product.config
}

# take_snapshot NAME OUTDIR: run snapshot.sh inside the container, copy results.
take_snapshot() {
  local name="$1" out="$2"
  podman cp "${PARITY_DIR}/snapshot.sh" "${name}:/usr/local/bin/parity-snapshot"
  podman cp "${PARITY_DIR}/snapshot-exclude.txt" "${name}:/usr/local/share/parity-snapshot-exclude.txt"
  podman cp "${PARITY_DIR}/normalise-ldif.pl" "${name}:/usr/local/share/parity-normalise-ldif.pl"
  podman exec "${name}" chmod 0755 /usr/local/bin/parity-snapshot
  podman exec "${name}" /usr/local/bin/parity-snapshot /tmp/parity-snapshot
  rm -rf "${out}"
  mkdir -p "${out}"
  podman cp "${name}:/tmp/parity-snapshot/." "${out}/"
  log "snapshot written to ${out}"
}
