var fieldsByLegacy = func() map[string]*Field {
	m := make(map[string]*Field)

	for _, f := range Fields {
		for _, key := range f.Legacy {
			m[key] = f
		}
	}

	return m
}()

// LegacyDrop is a legacy key that was not imported.
type LegacyDrop struct {
	Key    string
	Reason string
}

// applyLegacyKey imports one legacy key, or returns why it is not imported
// (a zero LegacyDrop: imported, or nothing to report).
func (r *Resolved) applyLegacyKey(key, value string) (LegacyDrop, error) {
	if f := fieldsByLegacy[key]; f != nil {
		if value == "" || (key == "PUBLICSERVICEHOSTNAME" && value == "UNSET") {
			return LegacyDrop{}, nil
		}

		// setup.pl enables strict server names only for "yes" (L5348); its
		// own default "TRUE" left them off.
		if key == "STRICTSERVERNAMEENABLED" {
			value = strconv.FormatBool(value == legacyYes)
		}

		if err := r.Set(f, value, SourceLegacy); err != nil {
			return LegacyDrop{}, fmt.Errorf("%s: %w", key, err)
		}

		return LegacyDrop{}, nil
	}

	if strings.HasSuffix(key, "PASSSET") {
		return LegacyDrop{key, reasonDerived}, nil
	}

	if reason, known := legacyDropped[key]; known {
		return LegacyDrop{key, reason}, nil
	}

	// setup.pl loadConfig kept every key and ignored those it never read,
	// so files written for containers carry extra keys: report, not fail.
	return LegacyDrop{key, reasonUnknown}, nil
}

// ApplyLegacy applies a setup.pl config file: KEY=VALUE lines, split on the
// first "=", with every double quote removed (as setup.pl loadConfig reads
// it). Empty values leave the key to the defaults. It returns the keys that
// were not imported, unknown keys included; a malformed line or an invalid
// value is an error.
func (r *Resolved) ApplyLegacy(data []byte) ([]LegacyDrop, error) {
	var (
		drops []LegacyDrop
		errs  []error
	)

	for n, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		key, value, ok := strings.Cut(line, "=")
		if !ok {
			errs = append(errs, fmt.Errorf("line %d: expected KEY=VALUE", n+1))

			continue
		}

		drop, err := r.applyLegacyKey(strings.TrimSpace(key), strings.TrimSpace(strings.ReplaceAll(value, `"`, "")))

		switch {
		case err != nil:
			errs = append(errs, fmt.Errorf("line %d: %w", n+1, err))
		case drop.Key != "":
			drops = append(drops, drop)
		}
	}

	slices.SortFunc(drops, func(a, b LegacyDrop) int { return strings.Compare(a.Key, b.Key) })

	return drops, errors.Join(errs...)
}
