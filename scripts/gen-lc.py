"""Generate the localconfig tables derived from carbonio-mailbox LC.java.

Outputs (internal/localconfig/):
  lcdocs.go      the "zmlocalconfig -i" key docs
  lcdefaults.go  every KnownKey default plus the .protect() (force-to-edit) set

Inputs, both read with `git show <tag>:<path>` from a carbonio-mailbox clone:
  common/src/main/java/com/zimbra/common/localconfig/LC.java   KnownKey declarations
                                                               with @Supported/@Reloadable,
                                                               default values, .protect()
  store/conf/msgs/ZsMsg.properties                             default-locale key docs

lcdocs.go only contains keys declared in LC.java that also have a
ZsMsg.properties entry, exactly the set LocalConfig.printDoc can print.

The pinned tag lives in scripts/lc-mailbox-tag (the Makefile reads it too).

  scripts/gen-lc.py                          ~/zextras/carbonio-mailbox @ pinned tag
  scripts/gen-lc.py --mailbox-repo DIR --tag TAG [--outdir DIR]
  go generate ./internal/localconfig/        (or: make generate)
"""

import argparse
import json
import os
import re
import subprocess
import sys

LC_PATH = "common/src/main/java/com/zimbra/common/localconfig/LC.java"
MSGS_PATH = "store/conf/msgs/ZsMsg.properties"
WRAP = 84
HERE = os.path.dirname(os.path.abspath(__file__))
CONSTANTS_PATH = "common/src/main/java/com/zimbra/common/util/Constants.java"


def git_show(repo, tag, path):
    return subprocess.run(
        ["git", "-C", repo, "show", f"{tag}:{path}"],
        check=True, capture_output=True,
    ).stdout


def logical_lines(text):
    """Java .properties logical lines (comments dropped, continuations joined)."""
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i].rstrip("\r").lstrip(" \t\f")
        i += 1
        if line == "" or line[0] in "#!":
            continue
        while True:
            trailing = len(line) - len(line.rstrip("\\"))
            if trailing % 2 == 1 and i < len(lines):
                line = line[:-1] + lines[i].rstrip("\r").lstrip(" \t\f")
                i += 1
            else:
                break
        yield line


def unescape(s):
    out = []
    j = 0
    while j < len(s):
        c = s[j]
        if c == "\\" and j + 1 < len(s):
            d = s[j + 1]
            if d == "u":
                out.append(chr(int(s[j + 2:j + 6], 16)))
                j += 6
                continue
            out.append({"t": "\t", "n": "\n", "r": "\r", "f": "\f"}.get(d, d))
            j += 2
            continue
        out.append(c)
        j += 1
    return "".join(out)


def parse_properties(raw):
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("latin-1")
    props = {}
    for line in logical_lines(text):
        j = 0
        while j < len(line):
            if line[j] == "\\":
                j += 2
                continue
            if line[j] in "=: \t\f":
                break
            j += 1
        rest = line[j:].lstrip(" \t\f")
        if rest[:1] in ("=", ":"):
            rest = rest[1:].lstrip(" \t\f")
        props[unescape(line[:j])] = unescape(rest)
    return props


def parse_flags(java):
    decl = re.compile(r"((?:@\w+\s*)*)public static final KnownKey (\w+)\s*=", re.M)
    return {m.group(2): ("Supported" in m.group(1), "Reloadable" in m.group(1))
            for m in decl.finditer(java)}


def chunks(text):
    parts, cur = [], ""
    for tok in re.findall(r"\S+\s*|\s+", text):
        if cur and len(cur) + len(tok) > WRAP:
            parts.append(cur)
            cur = ""
        cur += tok
    if cur:
        parts.append(cur)
    assert "".join(parts) == text
    return parts


def render(entries, tag):
    out = [
        "// Code generated by scripts/gen-lc.py; DO NOT EDIT.\n"
        "//\n"
        # REUSE-IgnoreStart
        "// SPDX-FileCopyrightText: 2026 Zextras <https://www.zextras.com>\n"
        "//\n"
        "// SPDX-License-Identifier: AGPL-3.0-only\n"
        # REUSE-IgnoreEnd
        "\n"
        "package localconfig\n"
        "\n"
        "// lcDocs holds the documentation printed by the legacy \"zmlocalconfig -i\"\n"
        "// and \"zmlocalconfig --all\": the default-locale ZsMsg.properties text of every\n"
        "// KnownKey declared in LC.java, with its @Supported and @Reloadable flags\n"
        f"// (carbonio-mailbox tag {tag}).\n"
        "var lcDocs = map[string]KeyDoc{\n"
    ]
    for key, doc, supported, reloadable in entries:
        out.append(f"\t{json.dumps(key)}: {{\n")
        out.append("\t\tDoc: " + " +\n\t\t\t".join(json.dumps(p, ensure_ascii=False)
                                                    for p in chunks(doc)) + ",\n")
        if supported:
            out.append("\t\tSupported: true,\n")
        if reloadable:
            out.append("\t\tReloadable: true,\n")
        out.append("\t},\n")
    out.append("}\n")
    return "".join(out)


def literal_end(src, i):
    """Index just past the string/char literal opening at src[i]."""
    quote, j = src[i], i + 1
    while src[j] != quote:
        j += 2 if src[j] == "\\" else 1
    return j + 1


def java_strip_comments(src):
    """Drop // and /* */ comments, leaving string/char literals untouched."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            j = literal_end(src, i)
            out.append(src[i:j])
            i = j
        elif src.startswith("//", i):
            i = src.find("\n", i)
            i = n if i < 0 else i
        elif src.startswith("/*", i):
            i = src.index("*/", i + 2) + 2
            out.append(" ")
        else:
            out.append(c)
            i += 1
    return "".join(out)


JAVA_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f",
                '"': '"', "'": "'", "\\": "\\"}


def java_string(lit):
    out, j = [], 1
    while j < len(lit) - 1:
        if lit[j] == "\\":
            d = lit[j + 1]
            if d == "u":
                out.append(chr(int(lit[j + 2:j + 6], 16)))
                j += 6
                continue
            out.append(JAVA_ESCAPES[d])
            j += 2
        else:
            out.append(lit[j])
            j += 1
    return "".join(out)


def parse_constants(java, pattern):
    """Evaluate `public static final long NAME = <expr>;` constants (Constants.java)."""
    env = {}
    for m in re.finditer(pattern, java):
        env[m.group(1)] = eval(re.sub(r"\b([A-Z_]+)\b", lambda n: str(env.get(n.group(1), n.group(1))),
                                      m.group(2)), {"__builtins__": {}})
    return env


TOKEN_PARTS = [
    ("str", r'"(?:[^"\\]|\\.)*"'),
    ("num", r"\d+(?:\.\d+)?[LlFfDd]?"),
    ("enum", r"[A-Za-z_]\w*\.\w+\.toString\(\)"),
    ("id", r"[A-Za-z_]\w*(?:\.[A-Z_]\w*)?"),
    ("op", r"[-+*/()]"),
]
TOKEN = re.compile(r"\s*(?:" + "|".join(f"(?P<{name}>{pat})" for name, pat in TOKEN_PARTS) + ")")

ID_LITERALS = {"true": "True", "false": "False", "null": "''", "Integer.MAX_VALUE": "2147483647"}


def translate_id(tok, expr, strings, consts):
    """Python source for a Java identifier in a KnownKey default."""
    if tok in ID_LITERALS:
        return ID_LITERALS[tok]
    if tok.startswith("Constants."):
        return str(consts[tok.split(".")[1]])
    if tok in strings:
        return repr(strings[tok])
    raise ValueError(f"unknown identifier {tok!r} in {expr!r}")


def translate_token(kind, tok, expr, strings, consts):
    """Python source for one Java token in a KnownKey default."""
    if kind == "str":
        return repr(java_string(tok))
    if kind == "num":
        return tok.rstrip("LlFfDd") if "." not in tok else repr(float(tok.rstrip("FfDd")))
    if kind == "enum":
        return repr(tok.split(".")[1])
    if kind == "id":
        return translate_id(tok, expr, strings, consts)
    return tok


def eval_default(expr, strings, consts):
    """Evaluate a KnownKey.newKey(<expr>) argument to its LC.get() text.

    Supports exactly what LC.java uses: string/number/boolean literals, `+`
    concatenation, constant arithmetic, Constants.MILLIS_PER_*,
    Integer.MAX_VALUE, same-class String constants and Enum.x.toString().
    Anything else aborts so a new construct cannot be silently mis-evaluated.
    """
    parts, pos = [], 0
    expr = expr.strip()
    while pos < len(expr):
        m = TOKEN.match(expr, pos)
        if not m or m.end() == pos:
            raise ValueError(f"unsupported default expression: {expr!r}")
        pos = m.end()
        kind = m.lastgroup
        parts.append(translate_token(kind, m.group(kind).strip(), expr, strings, consts))
    val = eval(" ".join(parts), {"__builtins__": {}})
    if isinstance(val, bool):
        return "true" if val else "false"
    return str(val)


def balanced(src, start):
    """Index just past the ')' closing the '(' at src[start]."""
    depth, i = 0, start
    while True:
        c = src[i]
        if c == '"':
            i += 1
            while src[i] != '"':
                i += 2 if src[i] == "\\" else 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1


def parse_defaults(java, consts):
    """Return ({key: default text}, {protected keys}) for every KnownKey in LC.java."""
    src = java_strip_comments(java)
    strings = {m.group(1): java_string(m.group(2)) for m in re.finditer(
        r'static final String (\w+)\s*=\s*("(?:[^"\\]|\\.)*")\s*;', src)}
    decl = re.compile(r"public static final KnownKey (\w+)\s*=\s*KnownKey\.newKey\(")
    defaults, protected = {}, set()
    for m in decl.finditer(src):
        end = balanced(src, m.end() - 1)
        key = m.group(1)
        defaults[key] = eval_default(src[m.end():end - 1], strings, consts)
        tail = src[end:src.index(";", end)]
        if re.fullmatch(r"(?:\s*\.\s*protect\(\s*\))?\s*", tail) is None:
            raise ValueError(f"unsupported KnownKey chain on {key}: {tail!r}")
        if ".protect" in tail:
            protected.add(key)
    n_decl = len(re.findall(r"public static final KnownKey ", src))
    if n_decl != len(defaults):
        raise ValueError(f"{n_decl} KnownKey declarations but {len(defaults)} parsed")
    return defaults, protected


def render_defaults(defaults, protected, tag):
    out = [
        "// Code generated by scripts/gen-lc.py; DO NOT EDIT.\n"
        "//\n"
        # REUSE-IgnoreStart
        "// SPDX-FileCopyrightText: 2026 Zextras <https://www.zextras.com>\n"
        "//\n"
        "// SPDX-License-Identifier: AGPL-3.0-only\n"
        # REUSE-IgnoreEnd
        "\n"
        "package localconfig\n"
        "\n"
        "// lcDefaults is a verbatim port of every KnownKey default declared in\n"
        f"// carbonio-mailbox (tag {tag}) common/src/main/java/com/zimbra/common/localconfig/LC.java.\n"
        "//\n"
        "// configd is the only local-config implementation left on a Carbonio node: the\n"
        "// Java LocalConfigCLI is gone and both /opt/zextras/bin/zmlocalconfig and\n"
        "// zmsetvars (bin/shutil.sh) resolve through \"configd localconfig\". A key that is\n"
        "// missing here and absent from localconfig.xml resolves to the empty string with\n"
        "// no diagnostic, which silently breaks the shell and Perl tooling that reads it\n"
        "// (e.g. zmmyinit asserting on ${zimbra_db_directory}/db.sql, or zmldappasswd\n"
        "// writing its temporary LDIF into ${zimbra_tmp_directory}). The full set is\n"
        "// therefore ported, not a hand-picked subset.\n"
        "//\n"
        "// Conversion rules applied to the Java declarations:\n"
        "//   - Java null defaults become \"\" (LC.get uses Strings.nullToEmpty).\n"
        "//   - Numeric and boolean defaults become their decimal / \"true\"|\"false\" text.\n"
        "//   - Constants.MILLIS_PER_*, Integer.MAX_VALUE and constant arithmetic are\n"
        "//     evaluated to their literal result.\n"
        "//   - ${key} references are left intact; Interpolate resolves them after the\n"
        "//     localconfig.xml overrides are merged.\n"
        "var lcDefaults = map[string]string{\n"
    ]
    for key in sorted(defaults):
        out.append(f"\t{json.dumps(key)}: {json.dumps(defaults[key], ensure_ascii=False)},\n")
    out.append(
        "}\n\n"
        "// lcProtected is the set of keys declared .protect() in LC.java\n"
        "// (KnownKey.needForceToEdit): editing them requires -f.\n"
        "var lcProtected = map[string]bool{\n")
    for key in sorted(protected):
        out.append(f"\t{json.dumps(key)}: true,\n")
    out.append("}\n")
    return "".join(out)


def write_go(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    subprocess.run(["gofmt", "-w", path], check=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mailbox-repo", default=os.path.expanduser("~/zextras/carbonio-mailbox"))
    with open(os.path.join(HERE, "lc-mailbox-tag"), encoding="utf-8") as f:
        pinned = f.read().strip()
    ap.add_argument("--tag", default=pinned)
    ap.add_argument("--outdir", default=os.path.join(HERE, "..", "internal", "localconfig"))
    args = ap.parse_args()

    java = git_show(args.mailbox_repo, args.tag, LC_PATH).decode("utf-8")
    consts = parse_constants(
        java_strip_comments(git_show(args.mailbox_repo, args.tag, CONSTANTS_PATH).decode("utf-8")),
        r"static final long (\w+)\s*=\s*([^;]+);")
    flags = parse_flags(java)
    props = parse_properties(git_show(args.mailbox_repo, args.tag, MSGS_PATH))
    entries = [(k, props[k], *flags[k]) for k in sorted(flags) if k in props]
    defaults, protected = parse_defaults(java, consts)
    if set(defaults) != set(flags):
        raise ValueError("KnownKey sets differ between flag and default parsers")

    docs = os.path.join(args.outdir, "lcdocs.go")
    write_go(docs, render(entries, args.tag))
    print(f"{docs}: {len(entries)} keys", file=sys.stderr)
    defs = os.path.join(args.outdir, "lcdefaults.go")
    write_go(defs, render_defaults(defaults, protected, args.tag))
    print(f"{defs}: {len(defaults)} keys, {len(protected)} protected", file=sys.stderr)


if __name__ == "__main__":
    main()
